-- CampusConnect Admin Panel schema for PostgreSQL 10+
-- Create the database first: createdb -U postgres campusvoice
-- Then load this file: psql -U postgres -d campusvoice -f database/campusconnect.sql
-- The file name is retained for compatibility; the target database is campusvoice.
-- Application records are intentionally not seeded. Add real platform data through
-- the application or its source systems after creating the schema.

CREATE SCHEMA IF NOT EXISTS public;

CREATE TABLE IF NOT EXISTS public.admin_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(190) NOT NULL UNIQUE,
  display_name VARCHAR(120) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(40) NOT NULL DEFAULT 'Platform admin',
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.institutes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  city VARCHAR(160) NOT NULL,
  email VARCHAR(190) NOT NULL,
  applied_on DATE NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'Pending',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_institutes_status ON public.institutes(status);

CREATE TABLE IF NOT EXISTS public.user_accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(160) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  joined_on DATE NOT NULL,
  role VARCHAR(40) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'Active',
  last_active_label VARCHAR(80) NOT NULL DEFAULT 'Never',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_user_accounts_role_status ON public.user_accounts(role, status);

CREATE TABLE IF NOT EXISTS public.posts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(240) NOT NULL,
  institute_id BIGINT NOT NULL REFERENCES public.institutes(id),
  post_type VARCHAR(40) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'Published',
  published_on DATE NOT NULL,
  likes_count INT NOT NULL DEFAULT 0,
  comments_count INT NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_posts_status ON public.posts(status);

CREATE TABLE IF NOT EXISTS public.reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(240) NOT NULL,
  snippet VARCHAR(500) NOT NULL,
  reporter_name VARCHAR(160) NOT NULL,
  reported_type VARCHAR(40) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'Open',
  created_on DATE NOT NULL,
  reason VARCHAR(180) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_reports_status ON public.reports(status);

CREATE TABLE IF NOT EXISTS public.audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_email VARCHAR(190) NOT NULL,
  admin_name VARCHAR(120) NOT NULL,
  action VARCHAR(100) NOT NULL,
  target VARCHAR(240) NOT NULL,
  details VARCHAR(1000) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

